# Build data/font8.bin: 256 glyphs x 8 rows, ASCII-ordered, from a C64 chargen.
# Set 2 of the chargen (offset 2048) is the lowercase/uppercase set:
#   screen code $01-$1A = a-z, $41-$5A = A-Z, $20-$3F = space..?, $00 = @
# PETSCII has no backslash, backquote, braces, tilde or pipe: drawn here.
import sys
cg = open(sys.argv[1], 'rb').read()
s2 = cg[2048:4096]
def g(sc): return s2[sc*8:sc*8+8]
font = bytearray(256*8)
def put(a, rows): font[a*8:a*8+8] = bytes(rows)
for a in range(0x20, 0x40): put(a, g(a))              # space ! " # ... ?
put(0x40, g(0x00))                                    # @
for a in range(0x41, 0x5B): put(a, g(a))              # A-Z  (set 2: $41-$5A)
put(0x5B, g(0x1B)); put(0x5D, g(0x1D))                # [ ]
put(0x5E, g(0x1E)); put(0x5F, g(0x64))                # ^ ,  _ (use low line graphic)
for a in range(0x61, 0x7B): put(a, g(a - 0x60))       # a-z  (set 2: $01-$1A)
# hand-drawn: \ ` { | } ~
put(0x5C, [0x00,0x60,0x30,0x18,0x0C,0x06,0x00,0x00])  # backslash
put(0x60, [0x30,0x18,0x00,0x00,0x00,0x00,0x00,0x00])  # backquote
put(0x7B, [0x0C,0x18,0x18,0x30,0x18,0x18,0x0C,0x00])  # {
put(0x7C, [0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x00])  # |
put(0x7D, [0x30,0x18,0x18,0x0C,0x18,0x18,0x30,0x00])  # }
put(0x7E, [0x00,0x00,0x32,0x4C,0x00,0x00,0x00,0x00])  # ~
put(0x7F, [0xFF]*8)                                    # DEL: block
put(0x00, [0x00]*8)
open(sys.argv[2], 'wb').write(font)
print("font8.bin written")
